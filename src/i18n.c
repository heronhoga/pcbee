void i18n_set_language(Language language)
{
    current_language = language == LANGUAGE_INDONESIAN ? LANGUAGE_INDONESIAN : LANGUAGE_ENGLISH;
}

Language i18n_language(void) { return current_language; }

const char *tr(const char *english)
{
    if (!english) return "";
    if (current_language == LANGUAGE_INDONESIAN) {
        for (size_t i = 0; i < sizeof(translations) / sizeof(translations[0]); ++i)
            if (strcmp(english, translations[i].english) == 0) return translations[i].indonesian;
    }
    return english;
}
